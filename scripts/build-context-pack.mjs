// Bundles the Context Pack templates in content/context-pack/ into data/context-templates.ts,
// so the AI roadmap page can copy, download and zip them without a server.
// Run with `npm run context-pack` after editing a template.
import fs from "node:fs"
import path from "node:path"

const root = path.join(process.cwd(), "content", "context-pack")

const files = []
;(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else files.push(path.relative(root, full).split(path.sep).join("/"))
  }
})(root)

// Every file listed in data/context-pack.ts needs a template, and every template needs a listing.
const listed = [...fs.readFileSync("data/context-pack.ts", "utf8").matchAll(/^\s+path: "([^"]+)",$/gm)].map((m) => m[1])
const missing = listed.filter((p) => !files.includes(p))
const unlisted = files.filter((p) => !listed.includes(p))
if (missing.length || unlisted.length) {
  console.error("Missing templates:", missing, "\nTemplates not listed in data/context-pack.ts:", unlisted)
  process.exit(1)
}

const entries = files
  .sort()
  .map((p) => `  ${JSON.stringify(p)}: ${JSON.stringify(fs.readFileSync(path.join(root, p), "utf8").replace(/\r\n/g, "\n"))},`)
  .join("\n")

fs.writeFileSync(
  "data/context-templates.ts",
  `// Generated by scripts/build-context-pack.mjs from content/context-pack/. Do not edit by hand.
// Loaded on demand by the AI roadmap page, so it never weighs down the first render.

export const templates: Record<string, string> = {
${entries}
}
`,
)
console.log(`data/context-templates.ts: ${files.length} templates`)
