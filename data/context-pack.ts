// The AI Project Context Pack: the Markdown files that give coding agents durable context.
// Templates live in content/context-pack/ and are bundled by scripts/build-context-pack.mjs.

export type Priority = "essential" | "recommended" | "conditional" | "optional"

export interface ContextFile {
  /** Path inside a project, which is also the template's path in content/context-pack/. */
  path: string
  category: CategoryId
  priority: Priority
  /** The problem it solves. */
  purpose: string
  includes: string[]
  when: string
  /** Which agents load it on their own. "Reference it" means you point the agent at it. */
  autoRead: string
  verify: string
  dependsOn: string[]
  update: string
}

