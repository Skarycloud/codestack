/** Every file in a pack, including the smaller packs it builds on. */
export function packFiles(id: (typeof packs)[number]["id"]) {
  const order = packs.map((p) => p.id)
  return packs.slice(0, order.indexOf(id) + 1).flatMap((p) => p.files)
}
